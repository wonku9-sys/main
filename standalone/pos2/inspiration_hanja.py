def hanja_characters(value):
    return tuple(dict.fromkeys(c for c in value if '\u3400'<=c<='\u9fff' or '\uf900'<=c<='\ufaff'))


def annotate(card):
    """Missing guides fail content validation rather than inventing readings."""
    characters=hanja_characters(card['text'])
    if not characters:return dict(card,reading='',character_glosses=())
    reading=READINGS[card['text']]
    glosses=tuple(f'{c}({GLOSSES[c]})' for c in characters)
    notes=[]
    if '之' in characters:notes.append('之는 이 문장들에서 대명사나 어조사로도 쓰입니다.')
    if '說' in characters:notes.append('이 문장의 說은 설명할 설이 아니라 기쁠 열로 읽습니다.')
    if '淫' in characters:notes.append('여기서 淫은 마음을 흐트러뜨리거나 지나치게 만든다는 뜻으로 쓰였습니다.')
    if '里' in characters:notes.append('里는 여기서 거리를 나타내는 단위인 리입니다.')
    if '者' in characters:notes.append('者는 여기서 사람이나 경우를 나타내는 말입니다.')
    detail='한글 독음: '+reading+'\n\n글자별 뜻·음 (기본 훈음, 같은 글자는 한 번만 표시)\n'+' · '.join(glosses)
    if notes:detail+='\n'+' '.join(notes)
    detail+='\n\n전체 뜻\n'+MEANINGS[card['text']]+'\n\n생활 속 해설\n'+card['explanation']
    return dict(card,reading=reading,character_glosses=glosses,meaning=MEANINGS[card['text']],explanation=detail)
